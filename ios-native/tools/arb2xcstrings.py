#!/usr/bin/env python3
"""Generates the native app's String Catalog and typed accessors from the Flutter ARB files.

The ARB files in lib/l10n stay the single source of truth (Crowdin manages them), so both apps
always ship the same strings. Run after changing any ARB file:

    python3 ios-native/tools/arb2xcstrings.py
"""

import json
import pathlib
import re

repo = pathlib.Path(__file__).resolve().parents[2]
arb_dir = repo / 'lib' / 'l10n'
out_dir = repo / 'ios-native' / 'ColdChat' / 'Resources'
swift_out = repo / 'ios-native' / 'ColdChat' / 'Localization' / 'L10n.swift'

# ARB locale tags that Apple spells differently.
apple_locale = {'no': 'nb'}

placeholder = re.compile(r'\{(\w+)\}')


def load(path):
    with open(path, encoding='utf-8') as f:
        return json.load(f)


template = load(arb_dir / 'app_en.arb')
keys = [k for k in template if not k.startswith('@')]


def placeholders(key):
    return list(template.get(f'@{key}', {}).get('placeholders', {}).keys())


def to_format(key, value):
    """Turns `{name}` placeholders into positional `%1$@` specifiers in the template's order."""
    names = placeholders(key)
    return placeholder.sub(lambda m: f'%{names.index(m.group(1)) + 1}$@' if m.group(1) in names else m.group(0), value.replace('%', '%%'))


strings = {}
for key in keys:
    strings[key] = {'extractionState': 'manual', 'localizations': {}}

locales = []
for path in sorted(arb_dir.glob('app_*.arb')):
    tag = path.stem[len('app_'):]
    locale = apple_locale.get(tag, tag)
    locales.append(locale)
    data = load(path)
    for key in keys:
        value = data.get(key)
        if not isinstance(value, str) or (value == '' and tag != 'en'):
            continue
        strings[key]['localizations'][locale] = {'stringUnit': {'state': 'translated', 'value': to_format(key, value)}}

catalog = {'sourceLanguage': 'en', 'strings': strings, 'version': '1.0'}
with open(out_dir / 'Localizable.xcstrings', 'w', encoding='utf-8') as f:
    json.dump(catalog, f, ensure_ascii=False, indent=2, sort_keys=True)
    f.write('\n')


def swift_name(key):
    return {'default': 'default_', 'repeat': 'repeat_', 'import': 'import_', 'continue': 'continue_'}.get(key, key)


lines = [
    '// Generated by ios-native/tools/arb2xcstrings.py from lib/l10n/*.arb. Do not edit.',
    '',
    'import Foundation',
    '',
    'enum L10n {',
    f'    static let locales = {json.dumps(sorted(locales))}',
    '',
]
for key in keys:
    names = placeholders(key)
    if names:
        params = ', '.join(f'_ {n}: String' for n in names)
        args = ', '.join(names)
        lines.append(f'    static func {swift_name(key)}({params}) -> String {{ Localization.string("{key}", {args}) }}')
    else:
        lines.append(f'    static var {swift_name(key)}: String {{ Localization.string("{key}") }}')
lines.append('}')
lines.append('')
swift_out.parent.mkdir(parents=True, exist_ok=True)
swift_out.write_text('\n'.join(lines), encoding='utf-8')
print(f'{len(keys)} strings, {len(locales)} locales')
