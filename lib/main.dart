import 'dart:async';

import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import 'package:hive_ce_flutter/hive_ce_flutter.dart';
import 'package:provider/provider.dart';
import 'package:wakelock_plus/wakelock_plus.dart';

import 'api/api_client.dart';
import 'api/recentmessages/recentmessages.dart';
import 'app.dart';
import 'data/filesharing/upload_queue_cubit.dart';
import 'data/live/live_channels_cubit.dart';
import 'data/notifications_cubit.dart';
import 'data/repositories/repositories.dart';
import 'hive_registrar.g.dart';
import 'tmi/client/client.dart';
import 'tmi/client/client_lookups.dart';
import 'tools/coldchat_binding.dart';

Future<void> main() async {
  ColdChatBinding.ensureInitialized();

  await WakelockPlus.enable();

  // Fonts aren't pub packages, so their license has to be added to the license page by hand.
  LicenseRegistry.addLicense(() async* {
    yield LicenseEntryWithLineBreaks(['Google Sans Flex'], await rootBundle.loadString('fonts/OFL.txt'));
  });

  unawaited(SystemChrome.setEnabledSystemUIMode(SystemUiMode.edgeToEdge));

  await Hive.initFlutter();
  // Generated by hive_ce_generator from every @HiveType, so a new stored model can't be left unregistered.
  Hive.registerAdapters();

  // The one HTTP client: every request to Twitch and the other services goes through it.
  final api = ApiClient();
  final repositories = await Repositories.open(api);
  final activeTwitchAccount = repositories.accounts.active;

  runApp(
    MultiProvider(
      providers: [
        ...repositories.providers,
        Provider<ApiClient>.value(value: api),
        Provider<Client>(
          create: (context) => Client(
            api: api,
            twitchAccount: activeTwitchAccount,
            accounts: repositories.accounts,
            triggers: repositories.triggers,
            channelRepository: repositories.channels,
            cacheRepository: repositories.emoteBadgeCache,
            whisperRepository: repositories.whispers,
            recentMessages: RecentMessages(enabled: () => repositories.settings.chatHistory, api: api),
          ),
        ),
        BlocProvider<NotificationsCubit>(create: (context) => NotificationsCubit()),
        // Above the channel views on purpose: an upload must survive switching
        // tabs and must never be awaited by the composer.
        BlocProvider<UploadQueueCubit>(create: (context) => UploadQueueCubit(api: api)),
        // Above the app, so the channel sheet (a route of its own) sees it as well as the tabs.
        BlocProvider<LiveChannelsCubit>(
          create: (context) {
            final client = context.read<Client>();
            return LiveChannelsCubit(
              helix: () => client.helixAsActive(repositories.accounts),
              logins: () => [for (final channel in client.channels.state) channel.name],
              channelChanges: client.channels.stream,
              accountChanges: repositories.accounts.activeChanges,
            );
          },
        ),
      ],
      child: const App(),
    ),
  );
}
